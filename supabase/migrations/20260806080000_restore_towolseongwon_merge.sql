-- [왜 되돌아갔나]
-- 통합이 **대표 외 레코드를 삭제**하는 방식이었다. 그런데 2026-07-03 "경남 신규 16개
-- 시군구 KAPT Golden Record 시딩"(b0c066e)이 "kapt_code가 complexes에 없으면 삽입"으로
-- 동작해, 삭제된 세 단지의 kapt_code를 누락으로 보고 **다시 만들었다**.
-- 그날 삽입된 791건 = 신규 16개 시군구 788건 + 이 3건이다.
--
-- 결과: 통합 결정이 소리 없이 무효화되고, 거래 5,192건은 전부 성원토월1단지에 남은 채
-- 나머지 셋은 거래 0건인 빈 페이지가 됐다. url_slug 는 이미
-- '창원시/성산구/상남동/토월성원아파트' 라서 URL과 화면 제목이 어긋나 있었다.
--
-- [이번엔 삭제하지 않는다]
-- status='merged' + successor_id 로 남긴다. 그러면 시더가 kapt_code 를 발견하므로
-- 다시 만들지 않는다 — 같은 회귀가 반복되지 않는다.
-- 앱은 status='active' 로 거르므로(검색·랭킹·지도·인근시세) 화면에서는 사라진다.
--
-- 세대수 합: 1,675 + 1,645 + 1,600 + 1,332 = 6,252 (2026-05-20 결정과 동일)
-- 통합 후 회전율: 5,192건 / 6,252세대 / 10년 = 연 8.3% (정상 범위)

-- 1) 대표 단지 — 이름과 세대수를 통합 기준으로 되돌린다(url_slug 는 이미 이 이름이다)
